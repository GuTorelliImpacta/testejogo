import { chromium } from '@playwright/test';
(async () => {
  const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium' });
  const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, serviceWorkers: 'block' });
  const p = await ctx.newPage();
  p.on('pageerror', e => console.log('ERR', e));
  p.on('console', m => { if (m.type()==='error') console.log('CONSOLE', m.text()); });
  p.on('requestfailed', r => console.log('REQFAIL', r.url()));
  p.on('response', r => { if (r.status()>=400) console.log('HTTP', r.status(), r.url()); });
  await p.goto('http://localhost:4181/');
  await p.screenshot({ path: '/tmp/claude-0/s/splash.png' });
  await p.getByText('ENTRAR').click();
  await p.waitForTimeout(1500);
  await p.screenshot({ path: '/tmp/claude-0/s/idle.png' });
  console.log(await p.evaluate(() => document.querySelector('.altina')!.outerHTML.length));
  console.log(await p.evaluate(() => localStorage.getItem('altina-da-sorte:v2')));
  await p.locator('button.play').click();
  await p.waitForTimeout(6000);
  await p.screenshot({ path: '/tmp/claude-0/s/drawing.png' });
  await b.close();
})();
